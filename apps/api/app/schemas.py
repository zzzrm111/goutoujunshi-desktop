from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field


class SessionCreate(BaseModel):
    mode: Literal["girlfriend", "advisor"] = "girlfriend"


class MessageCreate(BaseModel):
    content: str = Field(default="", max_length=12000)
    regenerate: bool = False
    realtime: bool = False
    attachment_ids: list[str] = Field(default_factory=list, max_length=4)


class AttachmentOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    kind: str
    original_name: str
    mime_type: str
    size: int
    analysis_status: str
    summary: str
    created_at: datetime
    url: str


class MessageOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    role: str
    content: str
    created_at: datetime
    attachments: list[AttachmentOut] = Field(default_factory=list)


class SessionOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    title: str
    mode: str
    updated_at: datetime


class SessionDetail(SessionOut):
    messages: list[MessageOut]


class MemoryStatus(BaseModel):
    allowed: bool
    paused: bool


class MemoryConsentUpdate(BaseModel):
    allowed: bool


class MemoryPauseUpdate(BaseModel):
    paused: bool


class MemoryCreate(BaseModel):
    kind: Literal["user_fact", "preference", "boundary", "relationship_state", "important_event", "hypothesis"] = "user_fact"
    content: str = Field(min_length=1, max_length=200)


class MemoryUpdate(BaseModel):
    content: str = Field(min_length=1, max_length=200)


class MemoryOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    kind: str
    content: str
    created_at: datetime
    updated_at: datetime


class AdultStatus(BaseModel):
    confirmed: bool


class AdultConsentUpdate(BaseModel):
    confirmed: bool


class SpeechTranscriptionOut(BaseModel):
    text: str
    language: str
    duration_ms: int | None
    provider: str


class SpeechSynthesisRequest(BaseModel):
    text: str = Field(min_length=1, max_length=12000)
    voice: str = Field(default="default", min_length=1, max_length=80)
    speed: float = Field(default=1.0, ge=0.5, le=2.0)
    # VoiceStudio extension: lower values trade a little polish for latency.
    num_step: int | None = Field(default=None, ge=1, le=64)
    # Speech styles generated by the relationship engine can include a short
    # delivery direction plus the character's configured speaking habits.
    emotion: str = Field(default="", max_length=500)
    emotion_vector: list[float] | None = Field(default=None, min_length=8, max_length=8)


class AttachmentAnalysisOut(BaseModel):
    id: str
    analysis_status: str
    summary: str


class AgentProfileOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    display_name: str
    personality: str
    background: str
    interests: str
    boundaries: str
    speech_style: str
    inner_mood: str
    current_focus: str
    recent_plan: str
    avoid_topics: str
    autonomy_level: int
    initiative_level: int
    initiative_cooldown_minutes: int
    last_initiative_at: datetime | None
    anger_sensitivity: int
    silent_duration_minutes: int
    updated_at: datetime


class AgentProfileUpdate(BaseModel):
    display_name: str = Field(min_length=1, max_length=40)
    personality: str = Field(min_length=1, max_length=1000)
    background: str = Field(min_length=1, max_length=1500)
    interests: str = Field(min_length=1, max_length=800)
    boundaries: str = Field(min_length=1, max_length=1000)
    speech_style: str = Field(min_length=1, max_length=800)
    inner_mood: str = Field(min_length=1, max_length=80)
    current_focus: str = Field(default="", max_length=1000)
    recent_plan: str = Field(default="", max_length=1000)
    avoid_topics: str = Field(default="", max_length=1000)
    autonomy_level: int = Field(ge=1, le=5)
    initiative_level: int = Field(ge=1, le=5)
    initiative_cooldown_minutes: int = Field(ge=5, le=1440)
    anger_sensitivity: int = Field(ge=1, le=5)
    silent_duration_minutes: int = Field(ge=5, le=240)


class RelationshipStateOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    mood: str
    trust: int
    affection: int
    irritation: int
    conflict_count: int
    silence_until: datetime | None
    last_trigger: str
    updated_at: datetime


class RelationshipStateUpdate(BaseModel):
    mood: str = Field(min_length=1, max_length=40)
    trust: int = Field(ge=0, le=100)
    affection: int = Field(ge=0, le=100)
    irritation: int = Field(ge=0, le=100)
    conflict_count: int = Field(ge=0, le=999)
    last_trigger: str = Field(default="", max_length=200)


class RelationshipRuleOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    name: str
    match_text: str
    event_type: str
    trigger: str
    trust_delta: int
    affection_delta: int
    irritation_delta: int
    needs_distance: bool
    silence_minutes: int
    priority: int
    enabled: bool
    created_at: datetime
    updated_at: datetime


class RelationshipRuleCreate(BaseModel):
    name: str = Field(min_length=1, max_length=80)
    match_text: str = Field(min_length=1, max_length=200)
    event_type: str = Field(default="custom", min_length=1, max_length=40)
    trigger: str = Field(default="自定义关系规则命中", max_length=200)
    trust_delta: int = Field(default=0, ge=-30, le=30)
    affection_delta: int = Field(default=0, ge=-30, le=30)
    irritation_delta: int = Field(default=0, ge=-50, le=50)
    needs_distance: bool = False
    silence_minutes: int = Field(default=0, ge=0, le=1440)
    priority: int = Field(default=50, ge=0, le=999)
    enabled: bool = True


class RelationshipRuleUpdate(RelationshipRuleCreate):
    pass


class AgentMemoryOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    kind: str
    content: str
    source: str
    importance: int
    enabled: bool
    created_at: datetime
    updated_at: datetime


class AgentMemoryCreate(BaseModel):
    kind: str = Field(default="self_fact", min_length=1, max_length=40)
    content: str = Field(min_length=1, max_length=300)
